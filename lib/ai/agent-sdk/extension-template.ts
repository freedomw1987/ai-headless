// ==============================================
// 1. Field type 推斷 (FR-22.2.1)
// ==============================================

export type FieldType = 'string' | 'text' | 'boolean' | 'datetime' | 'enum' | 'number';

/**
 * 從 field 名稱推斷 type
 * - *Date / *date → datetime
 * - is* / has* / *Completed → boolean
 * - price / amount / count / stock / quantity → number
 * - description / content / notes / text → text
 * - 其他 → string
 */
export function inferFieldType(fieldName: string): FieldType {
  const lower = fieldName.toLowerCase();

  // datetime
  if (/date$/i.test(lower)) return 'datetime';
  if (/at$/i.test(lower)) return 'datetime'; // publishedAt, createdAt 等
  if (lower === 'datetime') return 'datetime';

  // boolean
  if (/^(is|has)/.test(lower)) return 'boolean';
  if (/completed$/i.test(lower)) return 'boolean';

  // number
  const numberKeywords = ['price', 'amount', 'count', 'stock', 'quantity', 'total', 'age', 'score', 'rating'];
  if (numberKeywords.some((k) => lower.includes(k))) return 'number';

  // text
  const textKeywords = ['description', 'content', 'notes', 'bio', 'text', 'summary'];
  if (textKeywords.some((k) => lower.includes(k))) return 'text';

  return 'string';
}

export interface FieldSpec {
  name: string;
  type: FieldType;
  label: string;
}

export function inferFields(fieldNames: string[]): FieldSpec[] {
  return fieldNames.map((name) => ({
    name,
    type: inferFieldType(name),
    label: name.charAt(0).toUpperCase() + name.slice(1).replace(/([A-Z])/g, ' $1'),
  }));
}

