/**
 * FR-22.1.1: 產生 8 個檔案內容
 */
export function generateExtensionTemplate(input: ExtensionTemplateInput): ExtensionTemplateOutput {
  const { name, fields } = input;
  const fieldsList = inferFields(fields);
  const fieldsListWithAuto = [
    ...fieldsList,
    { name: 'createdAt', type: 'datetime' as FieldType, label: '建立時間' },
    { name: 'updatedAt', type: 'datetime' as FieldType, label: '更新時間' },
  ];

  const modelName = name.charAt(0).toUpperCase() + name.slice(1);
  const label = name.charAt(0).toUpperCase() + name.slice(1).replace(/-/g, ' ');
  const hasCompleted = fieldsList.some((f) => f.type === 'boolean');
  const hasDueDate = fieldsList.some((f) => f.type === 'datetime' && /date/i.test(f.name));

  const files: ExtensionFile[] = [];

  // 1. manifest.json
  const manifest = {
    name,
    version: '1.0.0',
    label,
    description: `${label} extension (auto-generated by Sprint 55)`,
    author: 'ai-headless admin',
    hooks: [`${name}.beforeCreate`],
    actions: hasCompleted ? [`${name}.complete`] : [],
    computed: hasDueDate ? [`${name}.remainingDays`] : [],
    permissions: [`${name}.create`, `${name}.read`, `${name}.update`, `${name}.delete`],
    dependencies: [],
    nav: {
      path: `/admin/crud/${name}`,
      label,
      order: 100,
    },
  };
  files.push({
    path: `extensions/${name}/manifest.json`,
    content: JSON.stringify(manifest, null, 2),
  });

  // 2. <name>-spec.json (path ends with spec.json)
  const spec = {
    name,
    label,
    requiresExtension: name,
    list: {
      allowColumnToggle: true,
      defaultColumns: ['createdAt', 'updatedAt'],
      views: [{ type: 'table', label: '表格' }],
    },
    models: [
      {
        name: modelName,
        label,
        description: `${label} model`,
        fields: fieldsListWithAuto.map((f) => ({
          name: f.name,
          type: f.type,
          label: f.label,
          validation: f.name === 'createdAt' || f.name === 'updatedAt' ? {} : { required: f.name === 'name' || f.name === 'title' },
          list: { defaultVisible: true },
        })),
      },
    ],
  };
  files.push({
    path: `extensions/${name}/spec.json`,
    content: JSON.stringify(spec, null, 2),
  });

  // 3. hooks/beforeCreate.ts (validateExtensionFiles expects 'beforeCreate.ts' but Sprint 12 uses 'before-create.ts')
  // 沿用 todo extension 命名: before-create.ts
  files.push({
    path: `extensions/${name}/hooks/before-create.ts`,
    content: HOOK_BEFORE_CREATE_TEMPLATE
      .replaceAll('{name}', name)
      .replaceAll('{modelName}', modelName),
  });

  // 4. actions/complete.ts (optional)
  if (hasCompleted) {
    files.push({
      path: `extensions/${name}/actions/complete.ts`,
      content: ACTION_COMPLETE_TEMPLATE
        .replaceAll('{name}', name)
        .replaceAll('{modelName}', modelName),
    });
  } else {
    // 仍需一個檔案, 但內容標 stub
    files.push({
      path: `extensions/${name}/actions/complete.ts`,
      content: `// No 'completed' field — stub action\nexport {};\n`,
    });
  }

  // 5. computed/remainingDays.ts (optional, or stub)
  if (hasDueDate) {
    files.push({
      path: `extensions/${name}/computed/remaining-days.ts`,
      content: COMPUTED_REMAINING_DAYS_TEMPLATE
        .replaceAll('{name}', name)
        .replaceAll('{modelName}', modelName),
    });
  } else {
    files.push({
      path: `extensions/${name}/computed/remaining-days.ts`,
      content: `// No 'dueDate' field — stub computed\nexport {};\n`,
    });
  }

  // 6. workflow/<name>-workflow.ts
  files.push({
    path: `extensions/${name}/workflow/${name}-workflow.ts`,
    content: WORKFLOW_TEMPLATE
      .replaceAll('{name}', name)
      .replaceAll('{modelName}', modelName),
  });

  // 7. examples/list-and-filter.ts
  files.push({
    path: `extensions/${name}/examples/list-and-filter.ts`,
    content: EXAMPLE_TEMPLATE
      .replaceAll('{name}', name)
      .replaceAll('{modelName}', modelName),
  });

  // 8. README.md
  const fieldsTable = fieldsListWithAuto
    .map((f) => `| \`${f.name}\` | ${f.type} | ${f.label} |`)
    .join('\n');
  const actionsList = hasCompleted
    ? `- \`${name}.complete\` — 切換 completed 狀態`
    : '- (無，無 boolean 欄位)';
  const computedList = hasDueDate
    ? `- \`${name}.remainingDays\` — 計算距 dueDate 剩餘天數`
    : '- (無，無 dueDate 欄位)';

  files.push({
    path: `extensions/${name}/README.md`,
    content: README_TEMPLATE
      .replaceAll('{label}', label)
      .replaceAll('{name}', name)
      .replace('{fieldsTable}', fieldsTable)
      .replace('{actionsList}', actionsList)
      .replace('{computedList}', computedList),
  });

  return { files };
}