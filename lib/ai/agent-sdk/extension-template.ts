const HOOK_BEFORE_CREATE_TEMPLATE = `/**
 * {modelName} beforeCreate hook (auto-generated by /extension create)
 * - 設定 createdAt / updatedAt
 */

// {modelName} 型別 (auto-generated from spec.json)
export interface {modelName} {
  id: string;
  createdAt: string;
  updatedAt: string;
  [key: string]: unknown;
}

export async function beforeCreate(data: Partial<{modelName}>): Promise<Partial<{modelName}>> {
  const now = new Date().toISOString();
  return {
    ...data,
    createdAt: now,
    updatedAt: now,
  };
}
`;

const ACTION_COMPLETE_TEMPLATE = `/**
 * {modelName} complete action (auto-generated by /extension create)
 * - 切換 completed 狀態
 */

// {modelName} 型別 (auto-generated from spec.json)
export interface {modelName} {
  id: string;
  createdAt: string;
  updatedAt: string;
  [key: string]: unknown;
}

export async function complete(item: {modelName}): Promise<{modelName}> {
  return {
    ...item,
    completed: !item.completed,
    updatedAt: new Date().toISOString(),
  };
}
`;

const COMPUTED_REMAINING_DAYS_TEMPLATE = `/**
 * {modelName} remainingDays computed (auto-generated by /extension create)
 * - 計算距 dueDate 剩餘天數
 */

// {modelName} 型別 (auto-generated from spec.json)
export interface {modelName} {
  id: string;
  dueDate?: string;
  createdAt: string;
  updatedAt: string;
  [key: string]: unknown;
}

export function remainingDays(item: {modelName}): number {
  if (!item.dueDate) return 0;
  const due = new Date(item.dueDate).getTime();
  const now = Date.now();
  return Math.ceil((due - now) / (1000 * 60 * 60 * 24));
}
`;

const WORKFLOW_TEMPLATE = `/**
 * {modelName} workflow (auto-generated by /extension create)
 * - draft → published 狀態機
 */

// {modelName} 型別 (auto-generated from spec.json)
export interface {modelName} {
  id: string;
  state?: string;
  createdAt: string;
  updatedAt: string;
  [key: string]: unknown;
}

export type {modelName}State = 'draft' | 'published';

const TRANSITIONS: Record<{modelName}State, {modelName}State[]> = {
  draft: ['published'],
  published: ['draft'],
};

export function canTransition(from: {modelName}State, to: {modelName}State): boolean {
  return TRANSITIONS[from]?.includes(to) ?? false;
}

export function transition(item: {modelName}, to: {modelName}State): {modelName} {
  if (!canTransition((item.state ?? 'draft') as {modelName}State, to)) {
    throw new Error(\`Cannot transition from \${item.state} to \${to}\`);
  }
  return {
    ...item,
    state: to,
    updatedAt: new Date().toISOString(),
  };
}
`;

const EXAMPLE_TEMPLATE = `/**
 * {modelName} examples (auto-generated by /extension create)
 * - 列出所有 + filter
 */

// {modelName} 型別 (auto-generated from spec.json)
export interface {modelName} {
  id: string;
  createdAt: string;
  updatedAt: string;
  [key: string]: unknown;
}

export async function listAll(): Promise<{modelName}[]> {
  const res = await fetch('/api/crud/{name}');
  return (await res.json()).items;
}

export async function filterByName(name: string): Promise<{modelName}[]> {
  const res = await fetch(\`/api/crud/{name}?name=\${encodeURIComponent(name)}\`);
  return (await res.json()).items;
}
`;

